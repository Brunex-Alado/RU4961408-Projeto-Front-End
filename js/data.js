window.Raizes = {
    money(value) {
        return value.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' });
    },
    getUnit() {
        return localStorage.getItem('raizes_unit') || 'recife';
    },
    setUnit(id) {
        localStorage.setItem('raizes_unit', id);
    },
    getCart() {
        try {
            return JSON.parse(localStorage.getItem('raizes_cart') || '[]');
        } catch {
            return [];
        }
    },
    setCart(cart) {
        localStorage.setItem('raizes_cart', JSON.stringify(cart));
        this.updateCartBadge();
    },
    updateCartBadge() {
        const quantity = this.getCart().reduce((sum, item) => sum + item.qty, 0);
        document.querySelectorAll('[data-cart-count]').forEach((element) => {
            element.textContent = quantity;
            element.hidden = quantity === 0;
        });
    },
    add(id) {
        const product = RAIZES_PRODUCTS.find((item) => item.id === id);
        if (!product) return;

        const unit = this.getUnit();
        if (!product.units.includes(unit)) {
            this.toast('Este item não está disponível nesta unidade.');
            return;
        }

        const cart = this.getCart();
        const line = cart.find((item) => item.id === id);
        if (line) {
            line.qty += 1;
        } else {
            cart.push({ id, qty: 1 });
        }

        this.setCart(cart);
        this.toast('Item adicionado ao pedido.');
    },
    change(id, delta) {
        const cart = this.getCart();
        const line = cart.find((item) => item.id === id);
        if (line) line.qty += delta;
        this.setCart(cart.filter((item) => item.qty > 0));
    },
    clearCart() {
        this.setCart([]);
    },
    getConsent() {
        try {
            return JSON.parse(localStorage.getItem('raizes_privacy_consent') || 'null');
        } catch {
            return null;
        }
    },
    getOrder() {
        try {
            return JSON.parse(localStorage.getItem('raizes_order') || 'null');
        } catch {
            return null;
        }
    },
    setOrder(order) {
        localStorage.setItem('raizes_order', JSON.stringify(order));
    },
    toast(message) {
        let element = document.getElementById('toast');
        if (!element) {
            element = document.createElement('div');
            element.id = 'toast';
            element.className = 'toast';
            document.body.appendChild(element);
        }
        element.textContent = message;
        element.hidden = false;
        clearTimeout(this._toast);
        this._toast = setTimeout(() => {
            element.hidden = true;
        }, 2800);
    },
    unitName() {
        return (RAIZES_UNITS.find((unit) => unit.id === this.getUnit()) || RAIZES_UNITS[0]).name;
    },
    initNav() {
        const toggle = document.querySelector('.menu-toggle');
        const navigation = document.querySelector('.nav-links');
        if (toggle && navigation) {
            toggle.addEventListener('click', () => navigation.classList.toggle('open'));
        }

        this.updateCartBadge();
        const unitSelect = document.querySelector('[data-unit-select]');
        if (unitSelect) {
            unitSelect.value = this.getUnit();
            unitSelect.addEventListener('change', () => {
                this.setUnit(unitSelect.value);
                this.toast('Unidade atualizada.');
                document.dispatchEvent(new Event('unitchange'));
            });
        }
    }
};

document.addEventListener('DOMContentLoaded', () => Raizes.initNav());
